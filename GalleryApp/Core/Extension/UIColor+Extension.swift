import UIKit

extension UIColor {
    static let primaryColor = UIColor(named: "PrimaryColor") ?? .systemBlue
    static let secondaryColor = UIColor(named: "SecondaryColor") ?? .black
    static let backgroundColor = UIColor(named: "BackgroundColor") ?? .white
    static let errorColor = UIColor(named: "ErrorColor") ?? .red
}
